def update_model_metadata(name: str, rows: int, metrics: str, path: str):
    with get_conn() as conn:
        conn.execute("""
            INSERT INTO model_metadata (model_name, last_trained_ts, training_rows, metrics, artifact_path)
            VALUES (?, datetime('now'), ?, ?, ?)
            ON CONFLICT(model_name) DO UPDATE SET
                last_trained_ts = excluded.last_trained_ts,
                training_rows   = excluded.training_rows,
                metrics         = excluded.metrics,
                artifact_path   = excluded.artifact_path
        """, (name, rows, metrics, path))
        conn.commit()


def get_reading_count() -> int:
    with get_conn() as conn:
        return conn.execute("SELECT COUNT(*) FROM sensor_readings").fetchone()[0]
