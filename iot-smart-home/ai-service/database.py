"""
AETHER AI Service — SQLite Database Layer
Schema:
  sensor_readings  — timestamped readings from every device
  anomaly_events   — detected anomalies with scores + explanations
  llm_interactions — audit log of every LLM call
  model_metadata   — last train time + metrics per model
"""
import sqlite3
import os
from pathlib import Path
from contextlib import contextmanager
from config import config


# Resolve DB path relative to project root
_DB_PATH = Path(__file__).parent.parent / config.DB_PATH
_DB_PATH.parent.mkdir(parents=True, exist_ok=True)


SCHEMA = """
-- -------------------------------------------------------
-- Core sensor readings  (one row per device per tick)
-- -------------------------------------------------------
CREATE TABLE IF NOT EXISTS sensor_readings (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    ts              DATETIME DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    device_id       TEXT     NOT NULL,
    device_name     TEXT     NOT NULL,
    device_type     TEXT     NOT NULL,
    room            TEXT     NOT NULL,
    state           INTEGER  NOT NULL,   -- 0 / 1
    power_watts     REAL     DEFAULT 0,
    -- Type-specific floats (NULL when not applicable)
    brightness      REAL,               -- lights
    temperature     REAL,               -- thermostat: current ambient
    target_temp     REAL,               -- thermostat: set point
    humidity        REAL,               -- thermostat
    fan_speed_num   REAL,               -- fan (0=off,1=low,2=med,3=high)
    battery_pct     REAL,               -- lock
    is_locked       INTEGER,            -- lock  0/1
    is_recording    INTEGER,            -- camera 0/1
    motion_detected INTEGER,            -- camera 0/1
    is_open         INTEGER,            -- window contact 0/1 (Batch 0)
    -- Metadata
    is_simulated    INTEGER  DEFAULT 1, -- 1 = generated by simulator
    anomaly_score   REAL     DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_sr_device_ts ON sensor_readings(device_id, ts);
CREATE INDEX IF NOT EXISTS idx_sr_ts        ON sensor_readings(ts);

-- -------------------------------------------------------
-- Anomaly events
-- -------------------------------------------------------
CREATE TABLE IF NOT EXISTS anomaly_events (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    ts              DATETIME DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    device_id       TEXT     NOT NULL,
    algorithm       TEXT     NOT NULL,  -- e.g. "IsolationForest"
    score           REAL     NOT NULL,
    threshold       REAL     NOT NULL,
    feature_values  TEXT,               -- JSON dict of top features
    explanation     TEXT,               -- plain-language (LLM or rule-based)
    suggested_action TEXT,
    acknowledged    INTEGER  DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_ae_ts ON anomaly_events(ts);

-- -------------------------------------------------------
-- LLM interaction audit log
-- -------------------------------------------------------
CREATE TABLE IF NOT EXISTS llm_interactions (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    ts              DATETIME DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    intent          TEXT,               -- "device_control" | "insight" | "automation" | "alert_explain"
    user_input      TEXT,
    function_called TEXT,               -- the tool/function name used
    raw_response    TEXT,
    validated       INTEGER  DEFAULT 0, -- 1 = passed schema validation
    executed        INTEGER  DEFAULT 0, -- 1 = action actually taken
    confirmed       INTEGER  DEFAULT 0  -- 1 = user confirmed (security actions)
);

-- -------------------------------------------------------
-- Model metadata (last train + eval metrics)
-- -------------------------------------------------------
CREATE TABLE IF NOT EXISTS model_metadata (
    model_name      TEXT     PRIMARY KEY,
    last_trained_ts DATETIME,
    training_rows   INTEGER,
    metrics         TEXT,               -- JSON dict: MAE, RMSE, precision, recall, etc.
    artifact_path   TEXT                -- relative path to .joblib file
);
"""


# Columns added after the first release. init_db() adds any that an
# existing database is missing, so old aether.db files keep working.
_MIGRATIONS = {
    "sensor_readings": [("is_open", "INTEGER")],
}


def _migrate(conn: sqlite3.Connection) -> None:
    for table, cols in _MIGRATIONS.items():
        existing = {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}
        for name, sqltype in cols:
            if name not in existing:
                conn.execute(f"ALTER TABLE {table} ADD COLUMN {name} {sqltype}")


def init_db():
    """Create tables if they don't exist, then apply column migrations."""
    with sqlite3.connect(str(_DB_PATH)) as conn:
        conn.executescript(SCHEMA)
        _migrate(conn)
        conn.commit()
    print(f"[DB] Initialized at {_DB_PATH}")


@contextmanager
def get_conn():
    """Context manager for a short-lived connection."""
    conn = sqlite3.connect(str(_DB_PATH), check_same_thread=False)
    conn.row_factory = sqlite3.Row
    try:
        yield conn
    finally:
        conn.close()


def insert_reading(row: dict):
    cols = ", ".join(row.keys())
    placeholders = ", ".join("?" * len(row))
    sql = f"INSERT INTO sensor_readings ({cols}) VALUES ({placeholders})"
    with get_conn() as conn:
        conn.execute(sql, list(row.values()))
        conn.commit()


def fetch_readings(device_id: str | None = None,
                   limit: int = 500,
                   hours: float = 24) -> list[dict]:
    sql = """
        SELECT * FROM sensor_readings
        WHERE ts >= datetime('now', ?)
    """
    params: list = [f"-{hours} hours"]
    if device_id:
        sql += " AND device_id = ?"
        params.append(device_id)
    sql += " ORDER BY ts DESC LIMIT ?"
    params.append(limit)

    with get_conn() as conn:
        rows = conn.execute(sql, params).fetchall()
    return [dict(r) for r in rows]


def fetch_recent_by_device(hours: float = 48) -> dict[str, list[dict]]:
    """Return readings grouped by device_id for ML pipelines."""
    rows = fetch_readings(limit=10_000, hours=hours)
    grouped: dict[str, list[dict]] = {}
    for r in rows:
        grouped.setdefault(r["device_id"], []).append(r)
    return grouped


